export function detectAutoLanguage(browserLang?: string, country?: string): string {
  // 1. If user previously selected a language, respect localStorage
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('diary_app_lang');
    if (saved && APP_LANGUAGES.some(l => l.code === saved)) return saved;
  }

  // 2. Check browser navigator language
  const raw = (browserLang || (typeof navigator !== 'undefined' ? navigator.language : '')).toLowerCase();
  const code = raw.split('-')[0];
  if (APP_LANGUAGES.some(l => l.code === code)) return code;

  // 3. Fallback based on country name
  if (country) {
    const c = country.toLowerCase();
    if (c.includes('india') || c.includes('bharat')) return 'hi';
    if (c.includes('spain') || c.includes('mexic') || c.includes('colomb') || c.includes('argent') || c.includes('chile') || c.includes('peru') || c.includes('venezuel')) return 'es';
    if (c.includes('france') || c.includes('belgi') || c.includes('senegal')) return 'fr';
    if (c.includes('german') || c.includes('austria') || c.includes('deutschland')) return 'de';
    if (c.includes('bangla')) return 'bn';
    if (c.includes('saudi') || c.includes('emirate') || c.includes('uae') || c.includes('egypt') || c.includes('qatar') || c.includes('kuwait') || c.includes('oman')) return 'ar';
    if (c.includes('brazil') || c.includes('portugal')) return 'pt';
    if (c.includes('russia')) return 'ru';
    if (c.includes('japan')) return 'ja';
    if (c.includes('china') || c.includes('taiwan') || c.includes('hong')) return 'zh';
    if (c.includes('pakistan')) return 'ur';
    if (c.includes('ital')) return 'it';
    if (c.includes('turk')) return 'tr';
    if (c.includes('indones')) return 'id';
    if (c.includes('korea')) return 'ko';
  }

  return 'en';
}

